const db = require("../database/db");

exports.getDashboardStatistics = async() => {
    const [
        totalStudents,
        totalTeachers,
        totalDepartments,
        totalClasses,
        totalSubjects,
        totalAcademicYears,
        totalTerms,
        totalEnrollments,
        totalAttendance,
        totalExaminations,
        totalResults,
        totalFees,
        totalPayments,
        totalAnnouncements,
        totalEvents,
        totalNotifications,
    ] = await Promise.all([
        db.student.count(),
        db.teacher.count(),
        db.department.count(),
        db.renamedclass.count(),
        db.subject.count(),
        db.academicyear.count(),
        db.term.count(),
        db.enrollment.count(),
        db.attendance.count(),
        db.examination.count(),
        db.result.count(),
        db.fee.count(),
        db.payment.count(),
        db.announcement.count(),
        db.event.count(),
        db.notification.count(),
    ]);

    return {
        totalStudents,
        totalTeachers,
        totalDepartments,
        totalClasses,
        totalSubjects,
        totalAcademicYears,
        totalTerms,
        totalEnrollments,
        totalAttendance,
        totalExaminations,
        totalResults,
        totalFees,
        totalPayments,
        totalAnnouncements,
        totalEvents,
        totalNotifications,
    };
};